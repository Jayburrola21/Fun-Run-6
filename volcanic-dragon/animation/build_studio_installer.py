"""Generate the one-paste Studio installer from the canonical Luau source."""
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SYSTEM = ROOT / "src" / "ReplicatedStorage" / "VolcanicDragon"
SOURCES = {
    "Config": ("ModuleScript", SYSTEM / "Config.luau"),
    "Timeline": ("ModuleScript", SYSTEM / "Timeline.luau"),
    "DragonRig": ("ModuleScript", SYSTEM / "DragonRig.luau"),
    "FireEffects": ("ModuleScript", SYSTEM / "FireEffects.luau"),
    "VolcanicDragonServer": ("Script", ROOT / "src/ServerScriptService/VolcanicDragonServer.server.luau"),
    "VolcanicDragonClient": ("LocalScript", ROOT / "src/StarterPlayer/StarterPlayerScripts/VolcanicDragonClient.client.luau"),
}

HEADER = """-- Generated by build_studio_installer.py. Run in the Studio Command Bar in Edit mode.
local RunService = game:GetService("RunService")
assert(RunService:IsStudio() and not RunService:IsRunning(), "Run the Volcanic Dragon installer in Roblox Studio Edit mode.")

local Source = {
"""

INSTALL = """}

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerScriptService = game:GetService("ServerScriptService")
local StarterPlayerScripts = game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts")
local ownerAttribute = "VolcanicDragonPackage"
local shared = ReplicatedStorage:FindFirstChild("VolcanicDragon")
if shared then
	assert(shared:IsA("Folder") and shared:GetAttribute(ownerAttribute), "ReplicatedStorage.VolcanicDragon already exists outside this package.")
end

local destinations = {
	ModuleScript = shared,
	Script = ServerScriptService,
	LocalScript = StarterPlayerScripts,
}

-- Preflight before editing anything, including an installation built with Rojo.
for _, entry in Source do
	local destination = destinations[entry.class]
	local current = destination and destination:FindFirstChild(entry.name)
	if current then
		assert(current.ClassName == entry.class and current:GetAttribute(ownerAttribute),
			"Cannot overwrite existing " .. current:GetFullName())
	end
end
if not shared then
	shared = Instance.new("Folder")
	shared.Name = "VolcanicDragon"
	shared:SetAttribute(ownerAttribute, true)
	shared.Parent = ReplicatedStorage
	destinations.ModuleScript = shared
end

for _, entry in Source do
	local destination = destinations[entry.class]
	local object = destination:FindFirstChild(entry.name) or Instance.new(entry.class)
	object.Name = entry.name
	object.Source = entry.code
	object:SetAttribute(ownerAttribute, true)
	if entry.class ~= "ModuleScript" then
		object.Enabled = true
	end
	object.Parent = destination
end
print("Volcanic Dragon installed. Import the rigged GLB as VolcanicDragon, then Play and use Test fire breath.")
"""


def long_string(text):
    delimiter = ""
    while f"]{delimiter}]" in text:
        delimiter += "="
    return f"[{delimiter}[{text}]{delimiter}]"


def main():
    entries = []
    for name, (kind, path) in SOURCES.items():
        source = path.read_text()
        entries.append(f'\t{{ name = "{name}", class = "{kind}", code = {long_string(source)} }},\n')
    (ROOT / "InstallVolcanicDragon.command.luau").write_text(HEADER + "".join(entries) + INSTALL)


if __name__ == "__main__":
    main()
